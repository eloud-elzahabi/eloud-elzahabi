function normalizeSizeKey(sizeStr) {
    return String(sizeStr || "")
        .replace(/ml/gi, "مل")
        .replace(/\s+/g, " ")
        .trim();
}

function isPerfumeCategory(category) {
    return PERFUME_OFFER_CATEGORIES.includes(category);
}

