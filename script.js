function getCartPerfumeCountBySize(sizeKey, excludeIndex = -1, itemsArr = cartItemsList) {
    const targetSize = normalizeSizeKey(sizeKey);
    let count = 0;
    if (!Array.isArray(itemsArr)) return 0;
    itemsArr.forEach((entry, idx) => {
        if (!entry || idx === excludeIndex) return;
        const entryCat = entry.category || "men";
        if (!isPerfumeCategory(entryCat)) return;
        if (normalizeSizeKey(entry.size) === targetSize) {
            count += Math.max(0, Number(entry.qty) || 0);
        }
    });
    return count;
}

function getRewardQuotaFromList(rewardSizeKey, modeFilter, itemsArr) {
    const normRewardSize = normalizeSizeKey(rewardSizeKey);
    const matchingRules = STRICT_EXACT_OFFERS.filter((rule) => {
        if (normalizeSizeKey(rule.rewardSize) !== normRewardSize) return false;
        if (modeFilter && rule.mode !== modeFilter) return false;
        return true;
    });

    if (!matchingRules.length) return { quota: 0, matchedRule: null };

    let totalQuota = 0;
    let matchedRule = null;

    matchingRules.forEach((rule) => {
        const triggerCount = getCartPerfumeCountBySize(rule.triggerSize, -1, itemsArr);
        const reqQty = Math.max(1, Number(rule.triggerQty) || 1);

        if (rule.mode === "free") {
            const sameSizeReward = normalizeSizeKey(rule.triggerSize) === normRewardSize;
            const bundleSize = sameSizeReward ? reqQty + 1 : reqQty;
            const freeSlots = Math.floor(triggerCount / bundleSize);
            if (freeSlots > 0) {
                totalQuota += freeSlots;
                if (!matchedRule) matchedRule = rule;
            }
        } else {
            // الزجاجات المستهلكة في عروض "اشترِ 2 = مجاناً" لا تُحسب مرة تانية في الخصم
            let availableTriggers = triggerCount;
            STRICT_EXACT_OFFERS.forEach((freeRule) => {
                if (freeRule.mode !== "free") return;
                if (normalizeSizeKey(freeRule.triggerSize) !== normalizeSizeKey(rule.triggerSize)) return;
                const freeReq = Math.max(1, Number(freeRule.triggerQty) || 1);
                const sameSize = normalizeSizeKey(freeRule.triggerSize) === normalizeSizeKey(freeRule.rewardSize);
                const freeBundle = sameSize ? freeReq + 1 : freeReq;
                availableTriggers -= Math.floor(triggerCount / freeBundle) * freeBundle;
            });

            if (availableTriggers >= reqQty) {
                const discSlots = Math.floor(availableTriggers / reqQty);
                totalQuota += discSlots;
                if (!matchedRule) matchedRule = rule;
            }
        }
    });

    return { quota: totalQuota, matchedRule };
}

function buildCartOfferAllocations(itemsArr = cartItemsList) {
    const list = Array.isArray(itemsArr) ? itemsArr : [];
    const allocations = list.map(() => ({
        matchedOffer: null,
        freeUnits: 0,
        discountedUnits: 0,
        discountPercent: 0,
        discountedPercent: 0
    }));

    const indicesByRewardSize = new Map();
    list.forEach((entry, idx) => {
        if (!entry) return;
        const entryCat = entry.category || "men";
        if (!isPerfumeCategory(entryCat)) return;
        const normSize = normalizeSizeKey(entry.size);
        const hasAnyRuleForSize = STRICT_EXACT_OFFERS.some(
            (r) => normalizeSizeKey(r.rewardSize) === normSize
        );
        if (!hasAnyRuleForSize) return;
        if (!indicesByRewardSize.has(normSize)) {
            indicesByRewardSize.set(normSize, []);
        }
        indicesByRewardSize.get(normSize).push(idx);
    });

    indicesByRewardSize.forEach((rowIndices, normSize) => {
        const freeInfo = getRewardQuotaFromList(normSize, "free", list);
        let remainingFree = Math.max(0, freeInfo.quota);
        const freeMeta = freeInfo.matchedRule
            ? (offersData.find((o) => o.id === freeInfo.matchedRule.id) || freeInfo.matchedRule)
            : null;

        if (remainingFree > 0) {
            for (let idx = rowIndices.length - 1; idx >= 0; idx--) {
                const rowIdx = rowIndices[idx];
                if (remainingFree <= 0) break;
                const itemQty = Math.max(1, Number(list[rowIdx].qty) || 1);
                const takeFree = Math.min(itemQty, remainingFree);
                if (takeFree > 0) {
                    allocations[rowIdx].freeUnits += takeFree;
                    allocations[rowIdx].matchedOffer = freeMeta;
                    allocations[rowIdx].discountPercent = 100;
                    remainingFree -= takeFree;
                }
            }
        }

        const discInfo = getRewardQuotaFromList(normSize, "discount", list);
        let remainingDisc = Math.max(0, discInfo.quota);
        const discPct = discInfo.matchedRule ? (Number(discInfo.matchedRule.discountPercent) || 50) : 50;
        const discMeta = discInfo.matchedRule
            ? (offersData.find((o) => o.id === discInfo.matchedRule.id) || discInfo.matchedRule)
            : null;

        if (remainingDisc > 0) {
            for (const idx of rowIndices) {
                if (remainingDisc <= 0) break;
                const itemQty = Math.max(1, Number(list[idx].qty) || 1);
                const alreadyFreeHere = allocations[idx].freeUnits;
                const eligibleQtyHere = Math.max(0, itemQty - alreadyFreeHere);
                const takeDisc = Math.min(eligibleQtyHere, remainingDisc);
                if (takeDisc > 0) {
                    allocations[idx].discountedUnits += takeDisc;
                    allocations[idx].discountedPercent = discPct;
                    if (!allocations[idx].matchedOffer) {
                        allocations[idx].matchedOffer = discMeta;
                        allocations[idx].discountPercent = discPct;
                    }
                    remainingDisc -= takeDisc;
                }
            }
        }
    });

    return allocations;
}

function evaluateOfferForItem(category, sizeKey, qty = 1, excludeCartIndex = -1) {
    const cleanQty = Math.max(1, Number(qty) || 1);
    if (!isPerfumeCategory(category)) {
        return { matchedOffer: null, freeUnits: 0, discountedUnits: 0, discountPercent: 0 };
    }

    if (excludeCartIndex >= 0 && Array.isArray(cartItemsList) && cartItemsList[excludeCartIndex]) {
        const allocations = buildCartOfferAllocations(cartItemsList);
        return allocations[excludeCartIndex] || {
            matchedOffer: null,
            freeUnits: 0,
            discountedUnits: 0,
            discountPercent: 0
        };
    }

    const normRewardSize = normalizeSizeKey(sizeKey);
    const currentAllocations = buildCartOfferAllocations(cartItemsList);

    let consumedFreeInCart = 0;
    let consumedDiscInCart = 0;
    cartItemsList.forEach((entry, i) => {
        if (!entry) return;
        const entryCat = entry.category || "men";
        if (!isPerfumeCategory(entryCat)) return;
        if (normalizeSizeKey(entry.size) !== normRewardSize) return;
        consumedFreeInCart += Number(currentAllocations[i]?.freeUnits) || 0;
        consumedDiscInCart += Number(currentAllocations[i]?.discountedUnits) || 0;
    });

    const previewList = cartItemsList.concat([{ category, size: sizeKey, qty: cleanQty }]);
    const freeInfo = getRewardQuotaFromList(normRewardSize, "free", previewList);
    const remainingFree = Math.max(0, freeInfo.quota - consumedFreeInCart);
    if (remainingFree > 0 && freeInfo.matchedRule) {
        const freeUnits = Math.min(cleanQty, remainingFree);
        const matchedMeta = offersData.find((o) => o.id === freeInfo.matchedRule.id) || freeInfo.matchedRule;
        return {
            matchedOffer: matchedMeta,
            freeUnits,
            discountedUnits: 0,
            discountPercent: 100
        };
    }

    const discInfo = getRewardQuotaFromList(normRewardSize, "discount", cartItemsList);
    const remainingDisc = Math.max(0, discInfo.quota - consumedDiscInCart);
    if (remainingDisc > 0 && discInfo.matchedRule) {
        const discountedUnits = Math.min(cleanQty, remainingDisc);
        const matchedMeta = offersData.find((o) => o.id === discInfo.matchedRule.id) || discInfo.matchedRule;
        return {
            matchedOffer: matchedMeta,
            freeUnits: 0,
            discountedUnits,
            discountPercent: Number(discInfo.matchedRule.discountPercent) || 50
        };
    }

    return { matchedOffer: null, freeUnits: 0, discountedUnits: 0, discountPercent: 0 };
}

function computeLineItemSubtotal(item, cartIndex = -1) {
    const qty = Math.max(1, Number(item.qty) || 1);
    const baseUnitPrice = Number(item.baseUnitPrice ?? item.unitPrice) || 0;
    const category = item.category || "men";

    if (!isPerfumeCategory(category)) {
        return qty * baseUnitPrice;
    }

    let evalRes;
    if (cartIndex >= 0 && Array.isArray(cartItemsList) && cartItemsList[cartIndex]) {
        const allocations = buildCartOfferAllocations(cartItemsList);
        evalRes = allocations[cartIndex];
    } else {
        evalRes = evaluateOfferForItem(category, item.size, qty, -1);
    }

    if (!evalRes || !evalRes.matchedOffer) {
        return qty * baseUnitPrice;
    }

    if (evalRes.freeUnits > 0 || evalRes.discountedUnits > 0) {
        const freeUnits = Math.min(qty, Number(evalRes.freeUnits) || 0);
        const discUnits = Math.min(qty - freeUnits, Number(evalRes.discountedUnits) || 0);
        const pct = evalRes.discountedPercent || (freeUnits > 0 ? 50 : (evalRes.discountPercent || 50));
        const discountedUnitPrice = Math.round(baseUnitPrice * (1 - pct / 100));
        const normalUnits = Math.max(0, qty - freeUnits - discUnits);
        return normalUnits * baseUnitPrice + discUnits * discountedUnitPrice;
    }

    return qty * baseUnitPrice;
}

function getCartTotals() {
    let totalCount = 0;
    let totalAmount = 0;
    cartItemsList.forEach((entry, idx) => {
        totalCount += Number(entry.qty) || 0;
        totalAmount += computeLineItemSubtotal(entry, idx);
    });
    return { totalCount, totalAmount };
}

