    function populatePriceElementWithOffer(containerEl, basePrice, category, sizeKey, qty, available, currencySuffix, dict) {
        containerEl.innerHTML = "";
        const offerRes = available ? evaluateOfferForItem(category, sizeKey, qty) : null;

        if (available && offerRes && offerRes.matchedOffer && offerRes.freeUnits > 0) {
            const freeSpan = document.createElement("span");
            freeSpan.className = "offer-free-price-text";
            freeSpan.textContent = dict.freeOfferPriceText || "Free ( Offer )";
            containerEl.appendChild(freeSpan);
            return;
        }

        if (available && offerRes && offerRes.matchedOffer && offerRes.discountedUnits > 0) {
            const pct = offerRes.discountPercent || 50;
            const discountedPrice = Math.round(basePrice * (1 - pct / 100));

            const oldPriceSpan = document.createElement("span");
            oldPriceSpan.className = "offer-old-price-strike";
            oldPriceSpan.textContent = `${basePrice} ${currencySuffix}`;

            const newPriceSpan = document.createElement("span");
            newPriceSpan.className = "offer-new-price-text";
            newPriceSpan.textContent = `${discountedPrice} ${currencySuffix}`;

            containerEl.appendChild(oldPriceSpan);
            containerEl.appendChild(newPriceSpan);
            return;
        }

        const priceSpan = document.createElement("span");
        priceSpan.className = available ? "" : "price-out-of-stock";
        priceSpan.textContent = `${basePrice} ${currencySuffix}`;
        containerEl.appendChild(priceSpan);

        if (!available) {
            const stockBadge = document.createElement("span");
            stockBadge.className = "out-of-stock-badge";
            stockBadge.textContent = dict.outOfStockText;
            containerEl.appendChild(stockBadge);
        }
    }

