    let isSyncingRoute = false;

    function buildHashForRoute(route) {
        if (!route || route.view === "home") return "#home";
        if (route.view === "products") {
            return `#products/${encodeURIComponent(route.category || "offers")}`;
        }
        if (route.view === "productDetail") {
            return `#product/${encodeURIComponent(route.id || "")}`;
        }
        if (route.view === "offerDetail") {
            return `#offer/${encodeURIComponent(route.id || "")}`;
        }
        if (route.view === "checkout") {
            return "#checkout";
        }
        return "#home";
    }

    function parseHashRoute(hashStr) {
        const raw = (hashStr || "").replace(/^#/, "").trim();
        if (!raw || raw === "home") {
            return { view: "home" };
        }
        if (raw === "products") {
            return { view: "products", category: "offers" };
        }
        if (raw.startsWith("products/")) {
            const cat = decodeURIComponent(raw.slice("products/".length)).trim() || "offers";
            return { view: "products", category: cat };
        }
        if (raw.startsWith("product/")) {
            const id = decodeURIComponent(raw.slice("product/".length)).trim();
            return { view: "productDetail", id };
        }
        if (raw.startsWith("offer/")) {
            const id = decodeURIComponent(raw.slice("offer/".length)).trim();
            return { view: "offerDetail", id };
        }
        if (raw === "checkout") {
            return { view: "checkout" };
        }
        return { view: "home" };
    }

    function pushRouteHash(route, replace = false) {
        if (isSyncingRoute) return;
        const targetHash = buildHashForRoute(route);
        if (window.location.hash === targetHash) return;

        if (replace) {
            const baseUrl = window.location.href.split("#")[0];
            window.history.replaceState(null, "", `${baseUrl}${targetHash}`);
        } else {
            window.location.hash = targetHash;
        }
    }

